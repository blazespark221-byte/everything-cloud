// Writes index.html from the voice timing: one host per scene, the voice tracks,
// the music bed and every sound effect at its film time.
//   node tools/build.mjs
// Scene visuals key off the same timing at runtime (assets/data/timing.js), so after
// re-running tools/voice.py, re-run this and the picture and sound stay in step.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const timing = JSON.parse(readFileSync(join(ROOT, "assets/data/timing.json"), "utf8"));
const sfx = JSON.parse(readFileSync(join(ROOT, "script/sfx.json"), "utf8"));
const scenes = Object.keys(timing);
const total = scenes.reduce((a, s) => a + timing[s].duration, 0);
const r3 = (v) => Math.round(v * 1000) / 1000;

// scene-local time of a cue: a line key ("q"), "key.e" for its end, "key@word" for a word inside
// the line (estimated by character position, as Kit.cues().w does), "dur" for the scene end, or seconds
function cueTime(scene, at) {
  if (typeof at === "number") return at;
  const T = timing[scene];
  if (at === "dur") return T.duration;
  if (at.includes("@")) {
    const [k, word] = at.split("@");
    const L = T.lines[k];
    if (!L) throw new Error(`unknown cue ${scene}.${at}`);
    const i = L.text.toLowerCase().indexOf(word.toLowerCase());
    if (i < 0) throw new Error(`no "${word}" in ${scene}.${k}`);
    return L.s + ((L.e - L.s) * i) / L.text.length;
  }
  const [k, edge] = at.split(".");
  const line = T.lines[k];
  if (!line) throw new Error(`unknown cue ${scene}.${at}`);
  return edge === "e" ? line.e : line.s;
}

const hosts = scenes
  .map(
    (s) =>
      `      <div id="${s}" data-composition-id="${s}" data-composition-src="compositions/${s}.html" data-start="${r3(timing[s].start)}" data-duration="${timing[s].duration}" data-track-index="1" data-track-kind="graphics" data-width="1920" data-height="1080"></div>`,
  )
  .join("\n");

const voices = scenes
  .map(
    (s) =>
      `      <audio id="vo-${s}" class="clip" src="assets/voice/${s}.mp3" data-start="${r3(timing[s].start)}" data-duration="${timing[s].duration}" data-track-index="2" data-volume="1"></audio>`,
  )
  .join("\n");

const music = existsSync(join(ROOT, "assets/music/bed.mp3"))
  ? `      <audio id="music" class="clip" src="assets/music/bed.mp3" data-start="0" data-duration="${r3(total)}" data-track-index="3" data-volume="1"></audio>`
  : "";

const used = {};
const effects = sfx.cues
  .map((c) => {
    const [scene, at, offset, file, volume] = c;
    const t = timing[scene].start + cueTime(scene, at) + (offset || 0);
    const base = file.replace(/\.[a-z0-9]+$/, "");
    used[base] = (used[base] || 0) + 1;
    const id = `sfx-${scene}-${base}-${used[base]}`;
    return `      <audio id="${id}" class="clip" src="assets/sfx/${file}" data-start="${r3(t)}" data-track-index="4" data-volume="${volume == null ? 0.35 : volume}"></audio>`;
  })
  .join("\n");

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>Specs Explains: Weird But True</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        width: 1920px;
        height: 1080px;
        overflow: hidden;
        background: #fbf7ee;
      }
    </style>
  </head>
  <body>
    <!-- Generated by tools/build.mjs from assets/data/timing.json and script/sfx.json. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="${r3(total)}" data-width="1920" data-height="1080">
${hosts}
${voices}
${music}
${effects}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
writeFileSync(join(ROOT, "index.html"), html);
console.log(`index.html: ${scenes.length} scenes, ${sfx.cues.length} effects, ${r3(total)} s`);
